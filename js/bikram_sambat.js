/**
 * BS मितिलाई AD (ई.सं.) मा रूपान्तरण गर्छ
 * @param {number} bsYear - विक्रम संवत् वर्ष (१९७० देखि २२००)
 * @param {number} bsMonth - महिना (१ = वैशाख, १२ = चैत)
 * @param {number} bsDay - गते (१ देखि ३२ सम्म)
 * @returns {Date} JavaScript Date object (UTC)
 */
function bsToAd(bsYear, bsMonth, bsDay) {
    if (bsYear < MIN_BS_YEAR || bsYear > MAX_BS_YEAR) {
        const adYearApprox = bsYear - 57;
        return new Date(Date.UTC(adYearApprox, bsMonth - 1, bsDay));
    }

    const startDays = BS_YEAR_START_DAYS[bsYear];
    const months = BS_CALENDAR_DATA[bsYear];
    let offset = 0;
    for (let i = 0; i < bsMonth - 1; i++) {
        offset += months[i];
    }
    offset += (bsDay - 1);

    return new Date((startDays + offset) * ONE_DAY_MS);
}

/**
 * AD (ई.सं.) मितिलाई BS (विक्रम संवत्) मा रूपान्तरण गर्छ
 * @param {number} adYear - Gregorian Year (1913 to 2144)
 * @param {number} adMonth - Gregorian Month (1-12)
 * @param {number} adDay - Gregorian Day (1-31)
 * @returns {{year: number, month: number, day: number, monthNameNp: string, monthNameEn: string}}
 */
function adToBs(adYear, adMonth, adDay) {
    const targetAd = new Date(Date.UTC(adYear, adMonth - 1, adDay));
    const targetDays = Math.floor(targetAd.getTime() / ONE_DAY_MS);

    if (targetDays < BS_YEAR_START_DAYS[MIN_BS_YEAR] || adYear > 2144) {
        const bsYear = adYear + 57;
        const bsMonth = ((adMonth + 8) % 12) + 1;
        return {
            year: bsYear,
            month: bsMonth,
            day: adDay,
            monthNameNp: BS_MONTH_NAMES_NP[bsMonth - 1] || "वैशाख",
            monthNameEn: BS_MONTH_NAMES_EN[bsMonth - 1] || "Baisakh"
        };
    }

    let estYear = Math.floor(adYear + 56.7);
    if (estYear < MIN_BS_YEAR) estYear = MIN_BS_YEAR;
    if (estYear > MAX_BS_YEAR) estYear = MAX_BS_YEAR;

    while (estYear < MAX_BS_YEAR && BS_YEAR_START_DAYS[estYear + 1] <= targetDays) {
        estYear++;
    }
    while (estYear > MIN_BS_YEAR && BS_YEAR_START_DAYS[estYear] > targetDays) {
        estYear--;
    }

    const bsYear = estYear;
    let remDays = targetDays - BS_YEAR_START_DAYS[bsYear];
    const months = BS_CALENDAR_DATA[bsYear];
    let bsMonth = 1;
    for (let m = 0; m < 12; m++) {
        if (remDays < months[m]) {
            bsMonth = m + 1;
            break;
        }
        remDays -= months[m];
    }
    const bsDay = remDays + 1;

    return {
        year: bsYear,
        month: bsMonth,
        day: bsDay,
        monthNameNp: BS_MONTH_NAMES_NP[bsMonth - 1] || "वैशाख",
        monthNameEn: BS_MONTH_NAMES_EN[bsMonth - 1] || "Baisakh"
    };
}

